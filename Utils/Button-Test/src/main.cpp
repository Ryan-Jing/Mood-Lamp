#include <Arduino.h>

/*------------------------------------------------------------------------------------------------*/
/* MACROS                                                                                         */
/*------------------------------------------------------------------------------------------------*/

#define BUTTON_PIN_POS_1 D7
#define BUTTON_PIN_POS_2 D8

/*------------------------------------------------------------------------------------------------*/
/* GLOBAL VARIABLES                                                                               */
/*------------------------------------------------------------------------------------------------*/



/*------------------------------------------------------------------------------------------------*/
/* FUNCTION PROTOTYPES                                                                            */
/*------------------------------------------------------------------------------------------------*/



/*------------------------------------------------------------------------------------------------*/
/* FUNCTION DEFINITIONS                                                                           */
/*------------------------------------------------------------------------------------------------*/

void setup() {
    pinMode(BUTTON_PIN_POS_1, INPUT_PULLUP);
    pinMode(BUTTON_PIN_POS_2, INPUT_PULLUP);
}

void loop() {
    if (digitalRead(BUTTON_PIN_POS_1) == LOW) {
        printf("Button 1 pressed\n");
    }
    if (digitalRead(BUTTON_PIN_POS_2) == LOW) {
        printf("Button 2 pressed\n");
    }
    delay(pdMS_TO_TICKS(100));
}
